"""
saleh_snapshot.py — immutable provenance snapshot of the Saleh/Qiyas
19-stage SCG registry.

Loading strategy (fail-closed):
    1. Load data/canonical_19_stage_registry.json (generated by
       scripts/generate_canonical_registry_snapshot.py).
    2. If not found, raise RegistrySnapshotMissing with instructions.
    3. Validate: exactly 19 layers, all IMPLEMENTED, P12 TERMINAL, no P13.

Ownership boundary (binding):
    This module is a READ-ONLY consumer of Saleh/Qiyas. It NEVER imports
    Saleh at runtime (only the generator script does). It NEVER mutates
    the snapshot JSON. It provides typed, immutable accessors only.
"""
